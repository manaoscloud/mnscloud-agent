/**
 * Website edge serving (storefront S1b).
 *
 * - Platform nginx edge: `website.edge.ensure` keeps the `*.<base>` wildcard certificate (Let's Encrypt
 *   DNS-01) and one edge server for `*.<base>` that sends `/` to webapps with the original Host. The
 *   certbot hooks never see the Agent token: they only exchange files with the Agent process, which
 *   publishes the challenge through the API, waits for the authoritative TXT and releases it.
 * - Platform webapps hosts: `website.site` installs (download, SHA-256, site-install.sh) or removes
 *   (site-remove.sh) the static snapshot of one site.
 */

export const WEBSITE_SITE_CAPABILITY = "mnscloud.webapps.site.v1";
export const WEBSITE_RENEW_BEFORE_MS = 30 * 24 * 60 * 60 * 1000;
export const WEBSITE_SITE_MAX_ARCHIVE_BYTES = 100 * 1024 * 1024;

const LABEL = "[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?";
const HOST = new RegExp(`^(?=.{1,253}$)${LABEL}(\\.${LABEL})+$`);
const SITE_ID = /^[0-9a-f]{32}$/;
const VERSION = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;
const SHA256 = /^[0-9a-f]{64}$/;
const CHALLENGE_VALUE = /^[A-Za-z0-9_-]{20,128}$/;

export function websiteBase(value: unknown): string {
  const base = String(value ?? "").trim().toLowerCase().replace(/\.$/, "");
  if (!HOST.test(base)) throw new Error(`Invalid website base: ${String(value ?? "")}`);
  return base;
}

export function wildcardCertName(base: string) {
  return `wildcard.${websiteBase(base)}`;
}

export function websiteEdgeConfigFile(dir: string, base: string) {
  return `${dir.replace(/\/+$/, "")}/${websiteBase(base)}.conf`;
}

export interface WebsiteEdgeRenderInput {
  base: string;
  sslEnabled: boolean;
  acmeRoot: string;
  apiUpstream: string;
  webappsUpstream: string;
  certificateDir: string;
  securityHeaders: string;
}

function proxyHeaders(proto: string) {
  return [
    "    proxy_http_version 1.1;",
    "    proxy_set_header Host $host;",
    "    proxy_set_header X-Real-IP $remote_addr;",
    "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
    `    proxy_set_header X-Forwarded-Proto ${proto};`,
  ].join("\n");
}

/**
 * Edge servers for `*.<base>`: port 80 answers ACME and redirects (or serves until the certificate
 * exists); 443 serves the wildcard certificate, `/api/` to the API and `/` to webapps (original Host).
 */
export function renderWebsiteEdgeConfig(input: WebsiteEdgeRenderInput) {
  const base = websiteBase(input.base);
  const site = `${
    proxyHeaders(input.sslEnabled ? "https" : "$scheme")
  }\n    proxy_pass ${input.webappsUpstream};`;
  const httpRoot = input.sslEnabled
    ? "  location / {\n    return 301 https://$host$request_uri;\n  }"
    : `  location / {\n${input.securityHeaders}\n${site}\n  }`;
  const common = `  if ($request_uri ~ "^//") {
    return 404;
  }

  location ^~ /.well-known/acme-challenge/ {
    root ${input.acmeRoot};
    default_type "text/plain";
    try_files $uri =404;
    access_log off;
  }`;
  const http = `# Generated by mnscloud-agent (website.edge.ensure) for *.${base}. Do not edit.
server {
  listen 80;
  listen [::]:80;
  server_name *.${base};

${common}

${httpRoot}
}
`;
  if (!input.sslEnabled) return http;
  const cert = input.certificateDir.replace(/\/+$/, "");
  return `${http}
server {
  listen 443 ssl;
  listen [::]:443 ssl;
  http2 on;
  server_name *.${base};

  ssl_certificate ${cert}/fullchain.pem;
  ssl_certificate_key ${cert}/privkey.pem;
  ssl_protocols TLSv1.2 TLSv1.3;
  ssl_session_cache shared:SSL:10m;
  ssl_session_timeout 10m;
  add_header Strict-Transport-Security "max-age=31536000" always;

${common}

  location /api/ {
${proxyHeaders("https")}
    proxy_pass ${input.apiUpstream};
  }

  location / {
${input.securityHeaders}
${proxyHeaders("https")}
    proxy_pass ${input.webappsUpstream};
  }
}
`;
}

/**
 * certbot manual hooks: `auth` hands the validation to the Agent (request file) and waits for its
 * answer; `cleanup` asks the Agent to release it. No token or API call lives in the hook.
 */
export function websiteAcmeHookScript() {
  return `#!/usr/bin/env bash
# Generated by mnscloud-agent (website.edge.ensure). Exchanges DNS-01 challenges with the Agent process.
set -euo pipefail
dir="$(cd "$(dirname "$0")" && pwd)"
id="$(printf '%s' "\${CERTBOT_VALIDATION:?}" | sha256sum | cut -c1-32)"
umask 077
case "\${1:-}" in
  auth)
    printf '%s\\n%s\\n' "\${CERTBOT_DOMAIN:?}" "\${CERTBOT_VALIDATION}" > "$dir/req.$id.tmp"
    mv -f "$dir/req.$id.tmp" "$dir/req.$id"
    for _ in $(seq 1 900); do
      if [[ -f "$dir/ok.$id" ]]; then rm -f "$dir/ok.$id"; exit 0; fi
      if [[ -f "$dir/err.$id" ]]; then cat "$dir/err.$id" >&2; rm -f "$dir/err.$id"; exit 1; fi
      sleep 1
    done
    echo "the MNSCloud Agent did not publish the DNS-01 challenge in time" >&2
    exit 1
    ;;
  cleanup)
    printf '%s\\n' "\${CERTBOT_VALIDATION}" > "$dir/cleanup.$id.tmp"
    mv -f "$dir/cleanup.$id.tmp" "$dir/cleanup.$id"
    ;;
  *)
    echo "usage: $0 auth|cleanup" >&2
    exit 2
    ;;
esac
`;
}

export function certbotWildcardArgs(input: { base: string; hook: string; email?: string | null }) {
  const base = websiteBase(input.base);
  const email = String(input.email ?? "").trim();
  return [
    "certonly",
    "--manual",
    "--preferred-challenges",
    "dns",
    "--manual-auth-hook",
    `${input.hook} auth`,
    "--manual-cleanup-hook",
    `${input.hook} cleanup`,
    "--cert-name",
    wildcardCertName(base),
    "-d",
    `*.${base}`,
    // The Agent renews it (website.edge.ensure); certbot.timer and renew --webroot must skip it.
    "--no-autorenew",
    "--keep-until-expiring",
    "--agree-tos",
    "--non-interactive",
    ...(email ? ["--email", email] : ["--register-unsafely-without-email"]),
  ];
}

/** `notAfter=Jan 18 12:00:00 2027 GMT` from `openssl x509 -enddate -noout`. */
export function parseOpensslEndDate(output: string): Date | null {
  const match = output.match(/notAfter=(.+)$/m);
  if (!match) return null;
  const date = new Date(match[1].trim());
  return Number.isNaN(date.getTime()) ? null : date;
}

export function needsWildcardRenewal(expiresAt: Date | null, now = new Date()) {
  return !expiresAt || expiresAt.getTime() - now.getTime() < WEBSITE_RENEW_BEFORE_MS;
}

/** A hook request file: `<domain>\n<validation>\n`; the domain must be `*.<base>` or `<base>`. */
export function parseHookRequest(text: string, base: string) {
  const [domain = "", value = ""] = text.split("\n").map((line) => line.trim());
  const expected = websiteBase(base);
  const normalized = domain.toLowerCase().replace(/^\*\./, "");
  if (normalized !== expected) throw new Error(`DNS-01 domain ${domain} is not *.${expected}`);
  if (!CHALLENGE_VALUE.test(value)) throw new Error("DNS-01 validation value is invalid");
  return { name: `_acme-challenge.${expected}`, value };
}

export interface WebsiteChallengeApi {
  create(name: string, value: string): Promise<{ challengeUUID: string; state: string }>;
  get(challengeUUID: string): Promise<{ state: string; errorCode?: unknown }>;
  release(challengeUUID: string): Promise<void>;
}

export interface WebsiteChallengeDeps {
  api: WebsiteChallengeApi;
  /** True when every authoritative nameserver of the base answers the TXT value. */
  txtVisible(name: string, value: string): Promise<boolean>;
  sleep(ms: number): Promise<void>;
  now(): number;
}

/** Publishes one validation, waits for the platform DNS write and the authoritative TXT. */
export async function publishWebsiteChallenge(
  deps: WebsiteChallengeDeps,
  name: string,
  value: string,
  timeoutMs = 600_000,
) {
  const created = await deps.api.create(name, value);
  const deadline = deps.now() + timeoutMs;
  let state = created.state;
  while (state !== "published") {
    if (state === "failed" || state === "released") {
      throw new Error(`DNS-01 challenge ${state} by the platform DNS worker`);
    }
    if (deps.now() > deadline) throw new Error("DNS-01 challenge was not published in time");
    await deps.sleep(5000);
    state = (await deps.api.get(created.challengeUUID)).state;
  }
  while (!(await deps.txtVisible(name, value))) {
    if (deps.now() > deadline) {
      throw new Error("DNS-01 TXT is not visible on every authoritative nameserver");
    }
    await deps.sleep(5000);
  }
  return created.challengeUUID;
}

export interface WebsiteSiteCommand {
  script: "site-install.sh" | "site-remove.sh";
  args: string[];
  artifactUrl?: string;
  sha256?: string;
}

/** Validated arguments of the webapps site scripts (the archive path is added after download). */
export function websiteSiteCommand(
  command: string,
  payload: Record<string, unknown>,
): WebsiteSiteCommand {
  const site = String(payload.site ?? "").trim().toLowerCase();
  if (!SITE_ID.test(site)) throw new Error("Website site id must be 32 hex characters");
  if (command === "remove") return { script: "site-remove.sh", args: ["--site", site] };
  if (command !== "install") throw new Error(`Unknown website site command: ${command}`);
  const version = String(payload.version ?? "").trim();
  const sha256 = String(payload.sha256 ?? "").trim().toLowerCase();
  const artifactUrl = String(payload.artifactUrl ?? "").trim();
  if (!VERSION.test(version)) throw new Error("Website snapshot version is invalid");
  if (!SHA256.test(sha256)) throw new Error("Website snapshot SHA-256 is invalid");
  let url: URL;
  try {
    url = new URL(artifactUrl);
  } catch {
    throw new Error("Website snapshot URL is invalid");
  }
  if (url.protocol !== "https:" || url.username || url.password) {
    throw new Error("Website snapshot URL must be https");
  }
  const hosts = Array.isArray(payload.hosts)
    ? payload.hosts.map((host) => String(host).trim().toLowerCase())
    : [];
  if (!hosts.length || hosts.length > 20 || !hosts.every((host) => HOST.test(host))) {
    throw new Error("Website snapshot hosts are invalid");
  }
  return {
    script: "site-install.sh",
    args: [
      "--site",
      site,
      "--version",
      version,
      "--sha256",
      sha256,
      ...hosts.flatMap((host) => ["--host", host]),
    ],
    artifactUrl: url.toString(),
    sha256,
  };
}

export async function sha256Hex(data: Uint8Array<ArrayBuffer>) {
  const digest = await crypto.subtle.digest("SHA-256", data);
  return Array.from(new Uint8Array(digest)).map((byte) => byte.toString(16).padStart(2, "0")).join(
    "",
  );
}
